// Bundles the ES modules under src/ into a single standalone slime-civ.html.
//
// Why bundle at all: browsers refuse to load ES modules over file://, so a
// double-clicked page of <script type="module"> fails with a CORS error. Rather
// than force everyone through a local web server, the source stays modular and
// this script flattens it into one classic <script> at build time.
//
// The transform is deliberately small, and only handles the module syntax this
// codebase actually uses:
//
//   import { a, b } from "./x.js";   ->  const { a, b } = __mod["x.js"];
//   export function f() {}           ->  function f() {}        (+ exported)
//   export const x = 1;              ->  const x = 1;           (+ exported)
//   export class C {}                ->  class C {}             (+ exported)
//
// Modules are emitted in dependency order (post-order DFS from main.js), so a
// module's dependencies always exist by the time its body runs. Import cycles
// are reported as an error rather than silently producing undefined bindings.

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve, relative, normalize } from "node:path";
import { fileURLToPath } from "node:url";
import { execSync } from "node:child_process";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const srcDir = join(root, "src");
const entry = join(srcDir, "main.js");
const shell = join(srcDir, "shell.html");
const outFile = join(root, "slime-civ.html");

const IMPORT_RE = /^[ \t]*import\s*\{([\s\S]*?)\}\s*from\s*["']([^"']+)["']\s*;?[ \t]*$/gm;
const BARE_IMPORT_RE = /^[ \t]*import\s+["'][^"']+["']\s*;?[ \t]*$/gm;

const modules = new Map();   // key -> { code, deps, exports }
const order = [];
const visiting = new Set();

/** Module key: path relative to src/, with forward slashes. */
function keyOf(absPath) {
  return relative(srcDir, absPath).split("\\").join("/");
}

function load(absPath, importedFrom) {
  const key = keyOf(absPath);
  if (modules.has(key)) return key;
  if (visiting.has(key)) {
    throw new Error("Import cycle involving " + key + " (imported from " + importedFrom + ")");
  }
  if (!existsSync(absPath)) {
    throw new Error("Missing module " + absPath + " (imported from " + importedFrom + ")");
  }
  visiting.add(key);

  const raw = readFileSync(absPath, "utf8");
  const deps = [];
  const exportNames = new Set();

  // 1. Rewrite imports, recursing into each dependency first.
  let code = raw.replace(IMPORT_RE, (_m, names, spec) => {
    const depAbs = resolve(dirname(absPath), spec);
    const depKey = load(depAbs, key);
    deps.push(depKey);
    // `import { a as b }` becomes destructuring rename `{ a: b }`.
    const cleaned = names.split(",")
      .map(s => s.trim())
      .filter(Boolean)
      .map(s => s.replace(/^([A-Za-z0-9_$]+)\s+as\s+([A-Za-z0-9_$]+)$/, "$1: $2"))
      .join(", ");
    return "const { " + cleaned + " } = __mod[" + JSON.stringify(depKey) + "];";
  });
  code = code.replace(BARE_IMPORT_RE, "");

  if (/^\s*import\s/m.test(code)) {
    const bad = code.match(/^\s*import\s.*$/m);
    throw new Error("Unsupported import form in " + key + ": " + bad[0].trim());
  }
  if (/^\s*export\s+default/m.test(code)) {
    throw new Error("Default exports are not supported by the bundler (" + key + ")");
  }

  // 2. Strip `export` keywords, recording what each module publishes.
  code = code.replace(/^[ \t]*export\s+(async\s+)?function\s+([A-Za-z0-9_$]+)/gm, (m, asyncKw, name) => {
    exportNames.add(name);
    return m.replace(/export\s+/, "");
  });
  code = code.replace(/^[ \t]*export\s+class\s+([A-Za-z0-9_$]+)/gm, (m, name) => {
    exportNames.add(name);
    return m.replace(/export\s+/, "");
  });
  code = code.replace(/^[ \t]*export\s+(const|let|var)\s+([A-Za-z0-9_$]+)/gm, (m, kind, name) => {
    exportNames.add(name);
    return m.replace(/export\s+/, "");
  });
  code = code.replace(/^[ \t]*export\s*\{([^}]*)\}\s*;?[ \t]*$/gm, (_m, names) => {
    for (const part of names.split(",")) {
      const bits = part.trim().split(/\s+as\s+/);
      if (bits[0]) exportNames.add((bits[1] || bits[0]).trim());
    }
    return "";
  });

  if (/^\s*export\s/m.test(code)) {
    const bad = code.match(/^\s*export\s.*$/m);
    throw new Error("Unsupported export form in " + key + ": " + bad[0].trim());
  }

  visiting.delete(key);
  modules.set(key, { key, code, deps, exports: [...exportNames] });
  order.push(key);
  return key;
}

load(entry, "(entry)");

// ---- Emit ------------------------------------------------------------------

const parts = [];
parts.push('"use strict";');
parts.push("// Generated by tools/build.js — edit the modules under src/, not this file.");
parts.push("var __mod = Object.create(null);");

for (const key of order) {
  const m = modules.get(key);
  const exportList = m.exports.length
    ? "return { " + m.exports.join(", ") + " };"
    : "return {};";
  parts.push(
    "__mod[" + JSON.stringify(key) + "] = (function () {\n"
    + m.code.replace(/^/gm, "  ") + "\n"
    + "  " + exportList + "\n"
    + "})();"
  );
}

// Build stamp (6.20): window.__BUILD = {stage, commit, dirty, time}. `stage` comes from game/VERSION (one line, e.g. "6.20"); commit and dirty from git (absent git: "nogit").
const gitOut = (cmd) => { try { return execSync(cmd, { cwd: root, stdio: ["ignore", "pipe", "ignore"] }).toString().trim(); } catch (e) { return null; } };
const stage = existsSync(join(root, "VERSION")) ? readFileSync(join(root, "VERSION"), "utf8").trim() : "?";
const commit = gitOut("git rev-parse --short HEAD"), status = gitOut("git status --porcelain");
const now = new Date(), p2 = (n) => String(n).padStart(2, "0");
const stamp = { stage, commit: commit || "nogit", dirty: status === null ? false : status.length > 0, time: now.getFullYear() + "-" + p2(now.getMonth() + 1) + "-" + p2(now.getDate()) + " " + p2(now.getHours()) + ":" + p2(now.getMinutes()) };
const bundle = "window.__BUILD = " + JSON.stringify(stamp) + ";\n(function () {\n" + parts.join("\n\n").replace(/^/gm, "  ") + "\n})();";

const html = readFileSync(shell, "utf8");
if (!html.includes("/*BUNDLE*/")) {
  throw new Error("src/shell.html is missing the /*BUNDLE*/ placeholder");
}
writeFileSync(outFile, html.replace("/*BUNDLE*/", () => bundle), "utf8");

const kb = (Buffer.byteLength(bundle, "utf8") / 1024).toFixed(1);
console.log("built slime-civ.html v" + stamp.stage + " " + stamp.commit + (stamp.dirty ? "+" : "") + " — " + order.length + " modules, " + kb + " KB of script");
for (const key of order) {
  const m = modules.get(key);
  if (process.env.VERBOSE) console.log("  " + key + "  (" + m.exports.length + " exports)");
}
